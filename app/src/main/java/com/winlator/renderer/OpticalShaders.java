package com.winlator.renderer;

/** Cinematic lens passes. All geometry is confined to the guest viewport. */
final class OpticalShaders {
    private OpticalShaders() {}

    private static final String HEADER = String.join("\n",
            "precision highp float;",
            "uniform sampler2D screenTexture, auxiliary, sceneMap, sceneScore;",
            "uniform vec2 origin, extent, stepUV, grade, lightMix, focusVignette, grainTuning;",
            "uniform float grainAmount, hasBloom;",
            "in vec2 vUV;",
            "layout(location=0) out vec4 outFragColor;",
            "float yOf(vec3 rgb) { return dot(rgb,vec3(0.2126,0.7152,0.0722)); }",
            "vec2 toUV(vec2 p) {",
            "    vec2 halfPixel=0.5/vec2(textureSize(screenTexture,0));",
            "    return clamp(origin+p*extent,origin+halfPixel,origin+extent-halfPixel);",
            "}",
            "float lumAt(vec2 p) { return yOf(texture(screenTexture,toUV(p)).rgb); }");

    static String capture() {
        return HEADER + String.join("\n", "",
                "void main() {",
                "    vec2 d=stepUV*0.31, p=vUV;",
                "    float a=lumAt(p+d), b=lumAt(p-d), c=lumAt(p+vec2(d.x,-d.y)), e=lumAt(p+vec2(-d.x,d.y));",
                "    float average=(a+b+c+e)*0.25, peak=max(max(a,b),max(c,e));",
                "    float local=(lumAt(p+vec2(stepUV.x*6.0,0))+lumAt(p-vec2(stepUV.x*6.0,0))",
                "                +lumAt(p+vec2(0,stepUV.y*5.0))+lumAt(p-vec2(0,stepUV.y*5.0)))*0.25;",
                "    float guard=smoothstep(0.23,0.39,p.y)*smoothstep(0.012,0.064,min(p.x,1.0-p.x));",
                "    float support=1.0;",
                "    if(hasBloom>0.0) support=mix(0.76,1.0,smoothstep(0.02,0.17,yOf(texture(auxiliary,toUV(p)).rgb)));",
                "    float lens=smoothstep(0.69,0.93,peak)*smoothstep(0.50,0.83,average)*smoothstep(0.075,0.24,peak-local);",
                "    float halo=smoothstep(0.66,0.92,peak)*smoothstep(0.45,0.75,average)*smoothstep(0.030,0.17,peak-local);",
                "    outFragColor=vec4(vec2(lens,halo)*support*guard,average,1);",
                "}");
    }

    static String spread(boolean horizontal) {
        return HEADER + (horizontal ? "\n#define HORIZONTAL 1\n" : "\n") + String.join("\n",
                "void main() {",
                "    vec3 center=texture(screenTexture,vUV).rgb;",
                "    float halo=center.g*0.227027;",
                "    for(int i=1;i<=2 && lightMix.y>0.0;++i) {",
                "        float offset=i==1 ? 1.384615 : 3.230769;",
                "        float weight=i==1 ? 0.316216 : 0.070270;",
                "        vec2 d=stepUV*offset;",
                "        halo+=(texture(screenTexture,vUV+d).g+texture(screenTexture,vUV-d).g)*weight;",
                "    }",
                "#ifdef HORIZONTAL",
                // A narrow horizontal falloff, with more closely spaced samples near the light.
                "    float flare=center.r*0.26;",
                "    for(int i=1;i<=7 && lightMix.x>0.0;++i) {",
                "        float n=float(i); vec2 d=vec2(0.0065*n*n*(0.72+grade.y*0.19),0);",
                "        float w=0.108*exp(-0.27*(n-1.0));",
                "        flare+=(texture(screenTexture,vUV+d).r+texture(screenTexture,vUV-d).r)*w;",
                "    }",
                "#else",
                "    float flare=lightMix.x<=0.0 ? 0.0 : center.r*0.70+0.15*(texture(screenTexture,vUV+0.55*stepUV).r+texture(screenTexture,vUV-0.55*stepUV).r);",
                "#endif",
                "    outFragColor=vec4(flare,halo,center.b,1);",
                "}");
    }

    static String composite() {
        return HEADER + String.join("\n", "",
                "uniform vec2 aperture;",
                "float noise(vec2 pixel) {",
                "    vec3 x=fract(vec3(pixel.xyx)*vec3(0.1031,0.1099,0.0973));",
                "    x+=dot(x,x.yzx+33.33); return fract((x.x+x.y)*x.z);",
                "}",
                "void main() {",
                "    vec4 src=texture(screenTexture,vUV); outFragColor=src;",
                "    vec2 p=(vUV-origin)/extent;",
                "    if(any(lessThan(p,vec2(0)))||any(greaterThanEqual(p,vec2(1)))||src.a<=0.003) return;",
                "    vec3 rgb=src.rgb; float y=yOf(rgb);",
                "    if(p.y<0.22 && y>0.68) return;",
                "    float amount=grade.x*(0.43+0.19*grade.y);",
                "    vec2 d=1.0/vec2(textureSize(screenTexture,0))/extent;",
                "    float contrast=max(abs(lumAt(p+vec2(d.x,0))-lumAt(p-vec2(d.x,0))),",
                "                       abs(lumAt(p+vec2(0,d.y))-lumAt(p-vec2(0,d.y))));",
                "    float textGuard=1.0-smoothstep(0.065,0.24,contrast);",
                "    float dialogue=1.0-smoothstep(0.20,0.34,p.y);",
                "    float protect=textGuard*(1.0-0.94*dialogue);",
                "    if(focusVignette.x>0.0 && protect>0.01) {",
                "        vec4 map=texture(sceneMap,p); vec4 score=texelFetch(sceneScore,ivec2(0),0);",
                "        float focus=(texture(sceneMap,vec2(0.34,0.46)).r+texture(sceneMap,vec2(0.5,0.46)).r",
                "                     +texture(sceneMap,vec2(0.66,0.46)).r)/3.0;",
                "        float trust=smoothstep(0.63,0.91,map.a)*smoothstep(0.47,0.80,score.r)*(1.0-smoothstep(0.12,0.42,map.b));",
                "        float skin=smoothstep(0.03,0.12,src.r-src.b)*smoothstep(0.01,0.07,src.r-src.g);",
                "        float defocus=smoothstep(0.040,0.17,focus-map.r)*trust*(1.0-0.86*skin);",
                "        if(defocus>0.006) {",
                "            vec3 sum=src.rgb*2.0; float total=2.0;",
                "            for(int i=0;i<8;++i) {",
                "                if(grade.y<2.0 && i%2==1) continue;",
                "                float angle=float(i)*0.785398;",
                "                vec2 q=clamp(p+vec2(cos(angle),sin(angle))*d*defocus*(2.0+3.6*grade.y)*focusVignette.x,vec2(0),vec2(1));",
                "                vec4 neighbor=texture(sceneMap,q);",
                "                vec3 color=texture(screenTexture,toUV(q)).rgb;",
                "                float weight=(1.0-smoothstep(0.024,0.095,abs(map.r-neighbor.r)))*(1.0-smoothstep(0.12,0.48,neighbor.b));",
                "                weight*=1.0-smoothstep(0.14,0.36,abs(y-yOf(color)));",
                "                sum+=color*weight; total+=weight;",
                "            }",
                "            rgb=mix(rgb,sum/total,defocus*protect*amount*focusVignette.x);",
                "        }",
                "    }",
                "    if(lightMix.x>0.0 || lightMix.y>0.0) {",
                "        vec3 optics=texture(auxiliary,p).rgb;",
                "        float room=1.0-smoothstep(0.56,0.96,y);",
                "        float blue=optics.r*lightMix.x*1.15;",
                "        float red=max(0.0,optics.g-smoothstep(0.57,0.91,y)*0.17)*lightMix.y*0.80;",
                "        rgb+=(vec3(0.21,0.63,1.0)*min(0.14,blue)+vec3(1.0,0.19,0.035)*min(0.14,red)*(1.0-0.40*hasBloom))*amount*protect*room;",
                "    }",
                "    if(focusVignette.y>0.0) {",
                "        vec2 q=(p-0.5)/aperture;",
                "        vec2 rim=abs(q)*2.0;",
                "        float falloff=smoothstep(0.48,1.28,length(rim));",
                "        vec2 clipped=1.0-smoothstep(vec2(0.91),vec2(1.0),rim);",
                "        float inside=(aperture.x<0.999 ? clipped.x : 1.0)*(aperture.y<0.999 ? clipped.y : 1.0);",
                "        rgb*=1.0-0.34*amount*focusVignette.y*falloff*inside*(0.28+0.72*textGuard)*(1.0-0.62*dialogue);",
                "    }",
                "    if(grainAmount>0.0) {",
                // Stationary grain coordinates avoid giving motion estimation artificial movement.
                "        vec2 cell=(gl_FragCoord.xy-origin*vec2(textureSize(screenTexture,0)))/grainTuning.x;",
                "        float organic=0.55*(noise(floor(cell))-noise(floor(cell)+vec2(91.0,17.0)))",
                "                      +0.45*(noise(floor(cell*0.51)+13.0)-noise(floor(cell*0.51)+61.0));",
                "        float mids=smoothstep(0.04,0.34,y)*(1.0-smoothstep(0.66,0.98,y));",
                "        float shadows=smoothstep(0.012,0.15,y)*(1.0-smoothstep(0.39,0.92,y));",
                "        rgb+=organic*mix(mids,shadows,grainTuning.y)*amount*grainAmount*protect*0.19;",
                "    }",
                "    outFragColor=vec4(clamp(rgb,0.0,1.0),src.a);",
                "}");
    }

    static String probe() {
        return HEADER + String.join("\n", "",
                "void main() {",
                "    float difference=0.0;",
                "    for(int j=0;j<4;++j) for(int i=0;i<4;++i) {",
                "        vec2 uv=toUV(vUV+(vec2(i,j)-1.5)/vec2(35,19));",
                "        vec3 d=abs(texture(screenTexture,uv).rgb-texture(auxiliary,uv).rgb);",
                "        difference=max(difference,max(d.r,max(d.g,d.b)));",
                "    }",
                "    outFragColor=vec4(difference,0,0,1);",
                "}");
    }
}
