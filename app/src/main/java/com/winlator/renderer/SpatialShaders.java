package com.winlator.renderer;

/**
 * GLES3 spatial filters. EASU and RCAS implement AMD FidelityFX FSR 1.0;
 * CAS implements AMD's sharpen-only default (green-coefficient) path.
 * Adapted from GPUOpen ffx_fsr1.h v1.20210629 and ffx_cas.h v1.20190610.
 * Exact GLSL reciprocal/square root replaces AMD hardware approximations;
 * bounded texelFetch replaces textureGather and keeps GLES3.0 compatibility.
 * AMD copyright and MIT permission: assets/licenses/AMD_FidelityFX.txt.
 * No frame interpolation, temporal history, or change to the game's render size.
 */
public final class SpatialShaders {
    private SpatialShaders() {}

    public static String getFxaaFragmentShader() {
        return String.join("\n",
            "precision highp float;",
            "uniform sampler2D screenTexture;",
            "uniform vec2 resolution;",
            "in vec2 vUV;",
            "layout(location = 0) out vec4 outFragColor;",
            "const vec3 lumaWeights = vec3(0.299, 0.587, 0.114);",
            "void main() {",
            "    vec2 inv = 1.0 / max(resolution, vec2(1.0));",
            "    vec4 center = texture(screenTexture, vUV);",
            "    vec3 nw = texture(screenTexture, vUV + vec2(-1.0,-1.0)*inv).rgb;",
            "    vec3 ne = texture(screenTexture, vUV + vec2(1.0,-1.0)*inv).rgb;",
            "    vec3 sw = texture(screenTexture, vUV + vec2(-1.0,1.0)*inv).rgb;",
            "    vec3 se = texture(screenTexture, vUV + vec2(1.0,1.0)*inv).rgb;",
            "    float lm = dot(center.rgb,lumaWeights);",
            "    float lnw=dot(nw,lumaWeights), lne=dot(ne,lumaWeights);",
            "    float lsw=dot(sw,lumaWeights), lse=dot(se,lumaWeights);",
            "    float lo=min(lm,min(min(lnw,lne),min(lsw,lse)));",
            "    float hi=max(lm,max(max(lnw,lne),max(lsw,lse)));",
            "    if (hi-lo < max(1.0/32.0,hi*0.125)) { outFragColor=center; return; }",
            "    vec2 dir=vec2(-((lnw+lne)-(lsw+lse)),(lnw+lsw)-(lne+lse));",
            "    float reduce=max((lnw+lne+lsw+lse)*(0.25/8.0),1.0/128.0);",
            "    dir=clamp(dir/(min(abs(dir.x),abs(dir.y))+reduce),vec2(-8.0),vec2(8.0))*inv;",
            "    vec3 a=0.5*(texture(screenTexture,vUV+dir*(1.0/3.0-0.5)).rgb+texture(screenTexture,vUV+dir*(2.0/3.0-0.5)).rgb);",
            "    vec3 b=a*0.5+0.25*(texture(screenTexture,vUV-dir*0.5).rgb+texture(screenTexture,vUV+dir*0.5).rgb);",
            "    float lb=dot(b,lumaWeights);",
            "    outFragColor=vec4((lb<lo || lb>hi)?a:b,center.a);",
            "}");
    }

    public static String getCasFragmentShader() {
        return String.join("\n",
            "precision highp float;",
            "uniform sampler2D screenTexture;",
            "uniform vec2 resolution;",
            "in vec2 vUV;",
            "layout(location = 0) out vec4 outFragColor;",
            "uniform float sharpness;",
            "vec4 loadPixel(ivec2 p) {",
            "    ivec2 size = textureSize(screenTexture, 0);",
            "    return texelFetch(screenTexture, clamp(p, ivec2(0), size - ivec2(1)), 0);",
            "}",
            "void main() {",
            "    ivec2 p=ivec2(vUV*vec2(textureSize(screenTexture,0)));",
            "    vec4 center=loadPixel(p);",
            "    float strength=clamp(sharpness,0.0,1.0);",
            "    if(strength<=0.0) {outFragColor=center;return;}",
            "    vec3 b=loadPixel(p+ivec2(0,-1)).rgb;",
            "    vec3 d=loadPixel(p+ivec2(-1,0)).rgb;",
            "    vec3 e=center.rgb;",
            "    vec3 f=loadPixel(p+ivec2(1,0)).rgb;",
            "    vec3 h=loadPixel(p+ivec2(0,1)).rgb;",
            "    // AMD CAS fast/default path: green-channel coefficient, sharpening only.",
            "    float mn=min(min(min(d.g,e.g),f.g),min(b.g,h.g));",
            "    float mx=max(max(max(d.g,e.g),f.g),max(b.g,h.g));",
            "    float amp=sqrt(clamp(min(mn,1.0-mx)/max(mx,0.00001),0.0,1.0));",
            "    float weight=-amp/(8.0-3.0*strength);",
            "    vec3 filtered=clamp(((b+d+f+h)*weight+e)/(1.0+4.0*weight),0.0,1.0);",
            "    // Continuous intensity extends AMD's default-to-maximum control down to Off.",
            "    outFragColor=vec4(mix(e,filtered,strength),center.a);",
            "}");
    }

    public static String getEasuFragmentShader() {
        return String.join("\n",
            "precision highp float;",
            "uniform sampler2D screenTexture;",
            "uniform vec2 resolution;",
            "in vec2 vUV;",
            "layout(location = 0) out vec4 outFragColor;",
            "uniform vec2 inputSize;",
            "vec4 loadPixel(ivec2 p) {",
            "    ivec2 size = textureSize(screenTexture, 0);",
            "    return texelFetch(screenTexture, clamp(p, ivec2(0), size - ivec2(1)), 0);",
            "}",
            "float easuLuma(vec3 color) {return color.b*0.5+(color.r*0.5+color.g);}",
            "void easuSet(inout vec2 dir,inout float len,float weight,float a,float b,float c,float d,float e) {",
            "    float dx=d-b, dy=e-a;",
            "    dir+=vec2(dx,dy)*weight;",
            "    float lx=clamp(abs(dx)/max(max(abs(d-c),abs(c-b)),0.00001),0.0,1.0);",
            "    float ly=clamp(abs(dy)/max(max(abs(e-c),abs(c-a)),0.00001),0.0,1.0);",
            "    len+=(lx*lx+ly*ly)*weight;",
            "}",
            "void easuTap(inout vec3 color,inout float weight,vec2 off,vec2 dir,vec2 len,float lob,float clp,vec3 sampleColor) {",
            "    vec2 v=vec2(off.x*dir.x+off.y*dir.y,-off.x*dir.y+off.y*dir.x)*len;",
            "    float d2=min(dot(v,v),clp);",
            "    float wb=(2.0/5.0)*d2-1.0;",
            "    float wa=lob*d2-1.0;",
            "    wb=wb*wb*(25.0/16.0)-(25.0/16.0-1.0);",
            "    wa*=wa;",
            "    float w=wb*wa;",
            "    color+=sampleColor*w;",
            "    weight+=w;",
            "}",
            "void main() {",
            "    // FsrEasuCon's pixel-center mapping, relative to the output viewport.",
            "    vec2 position=vUV*inputSize-0.5;",
            "    ivec2 fp=ivec2(floor(position));",
            "    vec2 pp=fract(position);",
            "    // AMD EASU 12-tap neighborhood; texelFetch replaces four gathers for GLES3.0.",
            "    //     b c",
            "    //   e f g h",
            "    //   i j k l",
            "    //     n o",
            "    vec3 b=loadPixel(fp+ivec2(0,-1)).rgb;",
            "    vec3 c=loadPixel(fp+ivec2(1,-1)).rgb;",
            "    vec3 e=loadPixel(fp+ivec2(-1,0)).rgb;",
            "    vec3 f=loadPixel(fp).rgb;",
            "    vec3 g=loadPixel(fp+ivec2(1,0)).rgb;",
            "    vec3 h=loadPixel(fp+ivec2(2,0)).rgb;",
            "    vec3 i=loadPixel(fp+ivec2(-1,1)).rgb;",
            "    vec3 j=loadPixel(fp+ivec2(0,1)).rgb;",
            "    vec3 k=loadPixel(fp+ivec2(1,1)).rgb;",
            "    vec3 l=loadPixel(fp+ivec2(2,1)).rgb;",
            "    vec3 n=loadPixel(fp+ivec2(0,2)).rgb;",
            "    vec3 o=loadPixel(fp+ivec2(1,2)).rgb;",
            "    float bl=easuLuma(b),cl=easuLuma(c),el=easuLuma(e),fl=easuLuma(f);",
            "    float gl=easuLuma(g),hl=easuLuma(h),il=easuLuma(i),jl=easuLuma(j);",
            "    float kl=easuLuma(k),ll=easuLuma(l),nl=easuLuma(n),ol=easuLuma(o);",
            "    vec2 dir=vec2(0.0);",
            "    float len=0.0;",
            "    easuSet(dir,len,(1.0-pp.x)*(1.0-pp.y),bl,el,fl,gl,jl);",
            "    easuSet(dir,len,pp.x*(1.0-pp.y),cl,fl,gl,hl,kl);",
            "    easuSet(dir,len,(1.0-pp.x)*pp.y,fl,il,jl,kl,nl);",
            "    easuSet(dir,len,pp.x*pp.y,gl,jl,kl,ll,ol);",
            "    float dir2=dot(dir,dir);",
            "    dir=dir2<(1.0/32768.0)?vec2(1.0,0.0):dir*inversesqrt(dir2);",
            "    len*=0.5;",
            "    len*=len;",
            "    float stretch=dot(dir,dir)/max(max(abs(dir.x),abs(dir.y)),0.00001);",
            "    vec2 len2=vec2(1.0+(stretch-1.0)*len,1.0-0.5*len);",
            "    float lob=0.5+((1.0/4.0-0.04)-0.5)*len;",
            "    float clp=1.0/lob;",
            "    vec3 min4=min(min(f,g),min(j,k));",
            "    vec3 max4=max(max(f,g),max(j,k));",
            "    vec3 sum=vec3(0.0);",
            "    float weight=0.0;",
            "    easuTap(sum,weight,vec2(0.0,-1.0)-pp,dir,len2,lob,clp,b);",
            "    easuTap(sum,weight,vec2(1.0,-1.0)-pp,dir,len2,lob,clp,c);",
            "    easuTap(sum,weight,vec2(-1.0,1.0)-pp,dir,len2,lob,clp,i);",
            "    easuTap(sum,weight,vec2(0.0,1.0)-pp,dir,len2,lob,clp,j);",
            "    easuTap(sum,weight,vec2(0.0,0.0)-pp,dir,len2,lob,clp,f);",
            "    easuTap(sum,weight,vec2(-1.0,0.0)-pp,dir,len2,lob,clp,e);",
            "    easuTap(sum,weight,vec2(1.0,1.0)-pp,dir,len2,lob,clp,k);",
            "    easuTap(sum,weight,vec2(2.0,1.0)-pp,dir,len2,lob,clp,l);",
            "    easuTap(sum,weight,vec2(2.0,0.0)-pp,dir,len2,lob,clp,h);",
            "    easuTap(sum,weight,vec2(1.0,0.0)-pp,dir,len2,lob,clp,g);",
            "    easuTap(sum,weight,vec2(1.0,2.0)-pp,dir,len2,lob,clp,o);",
            "    easuTap(sum,weight,vec2(0.0,2.0)-pp,dir,len2,lob,clp,n);",
            "    vec3 color=clamp(sum/max(weight,0.00001),min4,max4);",
            "    outFragColor=vec4(clamp(color,0.0,1.0),texture(screenTexture,vUV).a);",
            "}");
    }

    public static String getRcasFragmentShader() {
        return String.join("\n",
            "precision highp float;",
            "uniform sampler2D screenTexture;",
            "uniform vec2 resolution;",
            "in vec2 vUV;",
            "layout(location = 0) out vec4 outFragColor;",
            "uniform float sharpness;",
            "vec4 loadPixel(ivec2 p) {",
            "    ivec2 size = textureSize(screenTexture, 0);",
            "    return texelFetch(screenTexture, clamp(p, ivec2(0), size - ivec2(1)), 0);",
            "}",
            "void main() {",
            "    ivec2 p=ivec2(vUV*vec2(textureSize(screenTexture,0)));",
            "    vec4 center=loadPixel(p);",
            "    float strength=clamp(sharpness,0.0,1.0);",
            "    if(strength<=0.0) {outFragColor=center;return;}",
            "    vec3 b=loadPixel(p+ivec2(0,-1)).rgb;",
            "    vec3 d=loadPixel(p+ivec2(-1,0)).rgb;",
            "    vec3 e=center.rgb;",
            "    vec3 f=loadPixel(p+ivec2(1,0)).rgb;",
            "    vec3 h=loadPixel(p+ivec2(0,1)).rgb;",
            "    vec3 mn=min(min(b,d),min(f,h));",
            "    vec3 mx=max(max(b,d),max(f,h));",
            "    // AMD RCAS limiters. Guard constant black/white to avoid 0/0 in exact GLSL.",
            "    vec3 hitMin=min(mn,e)/max(4.0*mx,vec3(0.00001));",
            "    vec3 hitMax=(1.0-max(mx,e))/min(4.0*mn-4.0,vec3(-0.00001));",
            "    vec3 lobes=max(-hitMin,hitMax);",
            "    float lobe=max(-0.1875,min(max(lobes.r,max(lobes.g,lobes.b)),0.0))*strength;",
            "    vec3 result=(lobe*(b+d+f+h)+e)/(4.0*lobe+1.0);",
            "    outFragColor=vec4(clamp(result,0.0,1.0),center.a);",
            "}");
    }
}
