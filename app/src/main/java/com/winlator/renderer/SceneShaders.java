package com.winlator.renderer;

/** All coordinates use the OpenGL origin. Depth and material values are screen-space estimates. */
public final class SceneShaders {
    private SceneShaders() {}

    private static final String COMMON = String.join("\n",
            "precision highp float;",
            "uniform sampler2D screenTexture, referenceTexture, structureTexture, scoreTexture;",
            "uniform vec2 viewOrigin, viewExtent, mapStep, levels;",
            "uniform float phase, history;",
            "in vec2 vUV;",
            "layout(location=0) out vec4 outFragColor;",
            "vec2 sourceUV(vec2 p) { return viewOrigin + clamp(p,vec2(0.001),vec2(0.999))*viewExtent; }",
            "float luma(vec3 c) { return dot(c, vec3(0.2126,0.7152,0.0722)); }",
            "float distanceRGB(vec3 a, vec3 b) { vec3 d=abs(a-b); return max(d.r,max(d.g,d.b)); }",
            "vec3 reduced(vec2 p) {",
            "    vec2 d=mapStep*0.26;",
            "    return 0.25*(texture(screenTexture,sourceUV(p+d)).rgb+texture(screenTexture,sourceUV(p-d)).rgb",
            "        +texture(screenTexture,sourceUV(p+vec2(d.x,-d.y))).rgb",
            "        +texture(screenTexture,sourceUV(p+vec2(-d.x,d.y))).rgb);",
            "}");

    public static String capture() {
        return COMMON + "\nvoid main() { outFragColor=vec4(reduced(vUV),1); }";
    }

    public static String recognize() {
        return COMMON + String.join("\n", "",
                "void main() {",
                "    float sum=0.0, changed=0.0, energy=0.0; vec2 light=vec2(0.0), moments=vec2(0.0);",
                "    for(int j=0;j<5;++j) for(int i=0;i<8;++i) {",
                "        vec2 p=(vec2(i,j)+0.5)/vec2(8,5);",
                "        vec3 c=reduced(p);",
                "        float d=distanceRGB(c,texture(referenceTexture,p).rgb);",
                "        sum+=min(d,0.28); changed+=smoothstep(0.09,0.22,d);",
                "        float y=luma(c); moments+=vec2(y,y*y);",
                "        float b=smoothstep(0.39,0.93,y)*smoothstep(0.2,0.36,p.y);",
                "        light+=p*b; energy+=b;",
                "    }",
                "    float cut=max(smoothstep(0.075,0.125,sum/40.0),smoothstep(0.30,0.50,changed/40.0));",
                "    vec2 lightCenter=mix(vec2(0.28,0.83),light/max(0.001,energy),smoothstep(0.6,3.0,energy));",
                "    vec2 mean=moments/40.0;",
                "    float detail=smoothstep(0.00055,0.0035,mean.y-mean.x*mean.x);",
                "    outFragColor=vec4(history*(1.0-cut)*detail,lightCenter,cut*history);",
                "}");
    }

    public static String estimate() {
        return COMMON + String.join("\n", "",
                "vec3 sampleScene(vec2 delta) { return texture(screenTexture,vUV+delta*mapStep).rgb; }",
                "void main() {",
                "    vec3 c=sampleScene(vec2(0)); float y=luma(c);",
                "    float left=luma(sampleScene(vec2(-1,0))), right=luma(sampleScene(vec2(1,0)));",
                "    float down=luma(sampleScene(vec2(0,-1))), up=luma(sampleScene(vec2(0,1)));",
                "    float local=(left+right+down+up)*0.25;",
                "    float farMean=(luma(sampleScene(vec2(-4,0)))+luma(sampleScene(vec2(4,0)))",
                "                  +luma(sampleScene(vec2(0,-4)))+luma(sampleScene(vec2(0,4))))*0.25;",
                "    float contour=smoothstep(0.05,0.24,max(abs(left-right),abs(down-up))+abs(y-local));",
                "    float relief=clamp(0.62-0.39*vUV.y+0.54*(local-farMean)+0.15*(local-0.44),0.05,0.95);",
                "    float chroma=max(c.r,max(c.g,c.b))-min(c.r,min(c.g,c.b));",
                "    float specular=smoothstep(0.35,0.81,y)*(1.0-0.65*smoothstep(0.12,0.48,chroma));",
                "    float match=1.0-smoothstep(0.025,0.15,distanceRGB(c,texture(referenceTexture,vUV).rgb));",
                "    vec4 previous=texture(structureTexture,vUV);",
                "    float reuse=match*texelFetch(scoreTexture,ivec2(0),0).r;",
                "    relief=mix(relief,previous.r,reuse*0.76);",
                "    specular=mix(specular,previous.g,reuse*0.66);",
                "    float stability=mix(0.47,min(1.0,previous.a+0.27),reuse);",
                "    outFragColor=vec4(relief,specular,contour,stability);",
                "}");
    }

    public static String reconstruct() {
        return COMMON + String.join("\n", "",
                "void main() {",
                "    vec4 src=texture(screenTexture,vUV); outFragColor=src;",
                "    vec2 p=(vUV-viewOrigin)/viewExtent;",
                "    if(any(lessThan(p,vec2(0.0))) || any(greaterThan(p,vec2(1.0))) || src.a<0.99) return;",
                "    vec4 scene=texelFetch(scoreTexture,ivec2(0),0);",
                "    if(scene.r<=0.02) return;",
                "    vec4 map=texture(structureTexture,p);",
                "    if(map.b>0.88) return;",
                "    vec3 reference=texture(referenceTexture,p).rgb;",
                "    float residual=distanceRGB(src.rgb,reference);",
                "    float trust=(1.0-smoothstep(0.036,0.16,residual))*(1.0-smoothstep(0.16,0.88,map.b));",
                "    trust*=smoothstep(0.24,0.38,p.y)*(1.0-smoothstep(0.91,0.99,p.y));",
                "    trust*=smoothstep(0.032,0.10,min(p.x,1.0-p.x));",
                "    if(trust<=0.01) return;",
                "    vec2 pixel=1.0/vec2(textureSize(screenTexture,0));",
                "    float edge=max(distanceRGB(src.rgb,texture(screenTexture,vUV+vec2(pixel.x,0)).rgb),",
                "                   distanceRGB(src.rgb,texture(screenTexture,vUV+vec2(0,pixel.y)).rgb));",
                "    float warm=smoothstep(0.048,0.18,src.r-src.b)*smoothstep(0.024,0.13,src.r-src.g);",
                "    trust*= (1.0-smoothstep(0.09,0.34,edge))*(1.0-0.63*warm)*map.a*scene.r;",
                "    vec2 dx=vec2(mapStep.x,0), dy=vec2(0,mapStep.y);",
                "    float west=texture(structureTexture,p-dx).r, east=texture(structureTexture,p+dx).r;",
                "    float south=texture(structureTexture,p-dy).r, north=texture(structureTexture,p+dy).r;",
                "    vec2 gradient=vec2(east-west,north-south)/max(2.0*mapStep,vec2(0.001));",
                "    vec3 result=src.rgb;",
                "    if(levels.x>0.0) {",
                "        vec2 motion=vec2(sin(phase+3.0*p.y),0.5*cos(phase+2.0*p.x));",
                "        vec2 q=p+motion*(map.r-0.13)*levels.x*0.009*(1.0-map.b);",
                "        vec4 target=texture(structureTexture,q);",
                "        vec3 relocated=texture(screenTexture,sourceUV(q)).rgb;",
                "        float safe=(1.0-smoothstep(0.026,0.105,abs(target.r-map.r)))*(1.0-target.b);",
                "        safe*=1.0-smoothstep(0.032,0.14,distanceRGB(relocated,texture(referenceTexture,q).rgb));",
                "        result=mix(result,relocated,safe);",
                "    }",
                "    if(levels.y>0.0) {",
                "        vec2 direction=clamp(scene.gb,vec2(0.16,0.53),vec2(0.86,0.95))-p;",
                "        vec3 light=normalize(vec3(direction*1.55,0.47));",
                "        vec3 normal=normalize(vec3(-0.35*gradient,1.0));",
                "        float diffuse=dot(normal,light)-light.z;",
                "        float nearLight=exp(-2.9*dot(direction,direction));",
                "        float gain=levels.y*(0.22*diffuse+0.13*nearLight*(map.r-0.11));",
                "        vec3 relit=result*gain;",
                "        if(levels.y>=2.0) {",
                "            float spec=pow(max(0.0,dot(normal,normalize(light+vec3(0,0,1)))),10.0);",
                "            relit+=vec3(1.0,0.93,0.82)*map.g*spec*nearLight*0.13;",
                "            relit-=result*clamp((0.25*(west+east+south+north)-map.r)*2.8,0.0,0.20);",
                "        }",
                "        if(levels.y>=3.0) {",
                "            for(int i=1;i<=3;++i) {",
                "                vec2 q=p+direction*mapStep*float(i)*3.0;",
                "                float occluder=texture(structureTexture,q).r-map.r;",
                "                relit-=result*smoothstep(0.024,0.11,occluder)*0.034;",
                "            }",
                "        }",
                "        result+=clamp(relit,vec3(-0.17),vec3(0.21));",
                "    }",
                "    outFragColor=vec4(mix(src.rgb,clamp(result,0.0,1.0),trust),src.a);",
                "}");
    }

    public static String probe() {
        return COMMON + String.join("\n", "",
                "void main() {",
                "    float maximum=0.0;",
                "    for(int j=-1;j<=1;++j) for(int i=-1;i<=1;++i) {",
                "        vec2 p=sourceUV(vUV+vec2(i,j)/vec2(32,16));",
                "        maximum=max(maximum,distanceRGB(texture(screenTexture,p).rgb,texture(referenceTexture,p).rgb));",
                "    }",
                "    vec4 score=texelFetch(scoreTexture,ivec2(0),0);",
                "    outFragColor=vec4(maximum,score.r,score.a,1);",
                "}");
    }
}
